#!/usr/bin/env python3
"""Generate the device and Web message tables from shared/i18n/catalog.json.

The catalog is the single source for every user-visible string of the round
display (ESP32 and WebAssembly share moto_nav_ui) and of the Web shell. iOS
keeps Apple's String Catalog instead; check_catalogs.py verifies both.

Outputs (committed, so ESP-IDF and Emscripten builds need no Python):
  shared/nav_ui/generated/moto_nav_i18n.{h,c}  static tables for
                                               lv_translation_add_static()
  shared/i18n/generated/device_cjk_symbols.txt  CJK characters the device
                                               font must contain
  platforms/web/shell/i18n/messages.js          Web shell messages, plus the
                                               qps-ploc pseudo-locale

Run with --check to fail instead of writing when an output is stale.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
import re
import sys

REPO_ROOT = Path(__file__).resolve().parents[2]
CATALOG = REPO_ROOT / "shared/i18n/catalog.json"
DEVICE_HEADER = REPO_ROOT / "shared/nav_ui/generated/moto_nav_i18n.h"
DEVICE_SOURCE = REPO_ROOT / "shared/nav_ui/generated/moto_nav_i18n.c"
DEVICE_CJK_SYMBOLS = REPO_ROOT / "shared/i18n/generated/device_cjk_symbols.txt"
WEB_MESSAGES = REPO_ROOT / "platforms/web/shell/i18n/messages.js"
PSEUDO_LOCALE = "qps-ploc"
PSEUDO_ACCENTS = str.maketrans("aceinosuyACEINOSUY", "áçéîñöšüýÁÇÉÎÑÖŠÜÝ")
PARAMETER = re.compile(r"(\{[a-z_]+\})")

DEVICE_PREFIX = "device."
WEB_PREFIX = "web."
GENERATED_NOTE = (
    "Generated by scripts/i18n/build_catalog.py from shared/i18n/catalog.json."
    " Do not edit."
)


def load_catalog(path: Path = CATALOG) -> dict:
    with path.open(encoding="utf-8") as handle:
        return json.load(handle)


def c_literal(text: str) -> str:
    escaped = text.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{escaped}"'


def is_cjk(character: str) -> bool:
    code = ord(character)
    return (
        0x3000 <= code <= 0x303F  # CJK punctuation
        or 0x4E00 <= code <= 0x9FFF  # unified ideographs
        or 0xFF00 <= code <= 0xFFEF  # full-width forms
    )


def device_outputs(catalog: dict) -> dict[Path, str]:
    languages = catalog["languages"]
    keys = sorted(k for k in catalog["messages"] if k.startswith(DEVICE_PREFIX))

    header = "\n".join([
        f"/* {GENERATED_NOTE} */",
        "#pragma once",
        "",
        "#ifdef __cplusplus",
        'extern "C" {',
        "#endif",
        "",
        "/* Arguments for lv_translation_add_static(). */",
        "extern const char * const moto_nav_i18n_languages[];",
        "extern const char * const moto_nav_i18n_tags[];",
        "extern const char * const moto_nav_i18n_translations[];",
        "",
        "#ifdef __cplusplus",
        "}",
        "#endif",
        "",
    ])

    lines = [
        f"/* {GENERATED_NOTE} */",
        '#include "moto_nav_i18n.h"',
        "",
        "#include <stddef.h>",
        "",
        "const char * const moto_nav_i18n_languages[] = {",
    ]
    lines += [f"    {c_literal(language)}," for language in languages]
    lines += ["    NULL,", "};", "", "const char * const moto_nav_i18n_tags[] = {"]
    lines += [f"    {c_literal(key)}," for key in keys]
    lines += ["    NULL,", "};", "", "/* One row per tag, one column per language. */",
              "const char * const moto_nav_i18n_translations[] = {"]
    for key in keys:
        message = catalog["messages"][key]
        lines.append(f"    /* {key} */")
        lines += [f"    {c_literal(message[language])}," for language in languages]
    lines += ["};", ""]

    symbols = sorted({
        character
        for key in keys
        for language in languages
        for character in catalog["messages"][key][language]
        if is_cjk(character)
    })

    return {
        DEVICE_HEADER: header,
        DEVICE_SOURCE: "\n".join(lines),
        DEVICE_CJK_SYMBOLS: "".join(symbols) + "\n",
    }


def pseudo_localize(text: str) -> str:
    """Accented, about 40 % longer and bracketed, parameters untouched, so a
    cut or concatenated string is visible on screen (Microsoft's qps-ploc)."""
    parts = [part if PARAMETER.fullmatch(part) else part.translate(PSEUDO_ACCENTS)
             for part in PARAMETER.split(text)]
    padding = "~" * max(1, round(len(text) * 0.4))
    return f"[{''.join(parts)} {padding}]"


def web_outputs(catalog: dict) -> dict[Path, str]:
    keys = sorted(k for k in catalog["messages"] if k.startswith(WEB_PREFIX))
    if not keys:
        return {}
    tables = {
        language: {key: catalog["messages"][key][language] for key in keys}
        for language in catalog["languages"]
    }
    tables[PSEUDO_LOCALE] = {key: pseudo_localize(catalog["messages"][key]["en-US"]) for key in keys}
    body = json.dumps(tables, ensure_ascii=False, indent=2, sort_keys=True)
    return {WEB_MESSAGES: f"// {GENERATED_NOTE}\nwindow.MotoMessages = Object.freeze({body});\n"}


def all_outputs(catalog: dict) -> dict[Path, str]:
    outputs = device_outputs(catalog)
    outputs.update(web_outputs(catalog))
    return outputs


def stale_outputs(catalog: dict) -> list[Path]:
    stale = []
    for path, content in all_outputs(catalog).items():
        if not path.exists() or path.read_text(encoding="utf-8") != content:
            stale.append(path)
    return stale


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true",
                        help="fail when a generated file differs")
    arguments = parser.parse_args()
    catalog = load_catalog()

    if arguments.check:
        stale = stale_outputs(catalog)
        for path in stale:
            print(f"stale: {path.relative_to(REPO_ROOT)}", file=sys.stderr)
        return 1 if stale else 0

    for path, content in all_outputs(catalog).items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        print(f"wrote {path.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
